export function t(language, key, values = {}) {
  const message = messages[language]?.[key];
  if (message === undefined) throw new Error(`Missing translation: ${language}.${key}`);
  return message.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}
